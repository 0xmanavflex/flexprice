#!/usr/bin/env node
// Regenerates docs/ui-page-matrix.md: every route page, its pattern, and the
// shared kit pieces it composes. A page that names a bespoke component where a
// shared one belongs shows up here as a long "Page-specific" column.
//   node scripts/ui-page-matrix.mjs           write
//   node scripts/ui-page-matrix.mjs --check   fail if the file is stale
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const pagesDir = join(root, 'apps/console/src/pages')
const out = join(root, 'docs/ui-page-matrix.md')

const KIT = new Set([
  'PageHeader',
  'Page',
  'DetailHeader',
  'DetailShell',
  'DetailKit',
  'DetailTabs',
  'DetailList',
  'Section',
  'Panel',
  'EntityList',
  'FilterBar',
  'GridToolbar',
  'GridFooter',
  'SortMenu',
  'FormDialog',
  'FormPage',
  'FormCard',
  'FormActions',
  'Field',
  'EmptyState',
  'ConfirmDialog',
  'MetricRail',
  'StatCards',
  'Metric',
  'StatusBadge',
  'RowActionsMenu',
  'ResourceNavigation',
  'ConnectorCard',
  'ChartBox',
  'SimpleTable',
  'Properties',
  'ChoiceCards',
  'WorkflowStepper',
])

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const f = join(dir, n)
    return statSync(f).isDirectory() ? walk(f) : /Page\.tsx$/.test(n) ? [f] : []
  })
}

function pattern(name) {
  if (/ListPage|GridPage|IndexPage/.test(name)) return 'List'
  if (/DetailPage|Detail/.test(name)) return 'Detail'
  if (/FormPage|CreatePage|NewPage|EditPage/.test(name)) return 'Form'
  if (/Settings/.test(name)) return 'Settings'
  if (/Home|Revenue|Dashboard/.test(name)) return 'Dashboard'
  return 'Other'
}

const uiSrc = join(root, 'packages/ui/src')
function walkAll(dir) {
  return readdirSync(dir).flatMap((n) => {
    const f = join(dir, n)
    if (statSync(f).isDirectory())
      return /node_modules|primitives|reui|blocks|examples|^ui$/.test(n) ? [] : walkAll(f)
    return /\.tsx?$/.test(n) && !/\.(stories|test)\./.test(n) ? [f] : []
  })
}
const uiFiles = walkAll(uiSrc)
const textOf = new Map(uiFiles.map((f) => [f, readFileSync(f, 'utf8')]))
const owner = new Map()
for (const [f, t] of textOf)
  for (const m of t.matchAll(/export\s+(?:function|const|class)\s+([A-Z][A-Za-z0-9]*)/g))
    if (!owner.has(m[1])) owner.set(m[1], f)

// Kit pieces a component reaches, following its UI-package imports two levels deep.
function reach(ids, depth, seen = new Set()) {
  const kit = new Set()
  for (const id of ids) {
    if (KIT.has(id)) kit.add(id)
    const file = owner.get(id)
    if (!file || seen.has(file) || depth === 0) continue
    seen.add(file)
    const names = new Set()
    for (const m of textOf.get(file).matchAll(/import\s*\{([^}]+)\}\s*from\s*'[^']+'/gs))
      for (const part of m[1].split(',')) {
        const n = part
          .trim()
          .replace(/^type\s+/, '')
          .split(/\s+as\s+/)[0]
        if (/^[A-Z]/.test(n)) names.add(n)
      }
    for (const k of reach(names, depth - 1, seen)) kit.add(k)
  }
  return kit
}

const rows = walk(pagesDir)
  .sort()
  .map((file) => {
    const src = readFileSync(file, 'utf8')
    const name = file.split('/').pop().replace('.tsx', '')
    const imported = new Set()
    for (const m of src.matchAll(/import\s*\{([^}]+)\}\s*from\s*'(@fp\/ui[^']*)'/gs)) {
      for (const part of m[1].split(',')) {
        const id = part
          .trim()
          .replace(/^type\s+/, '')
          .split(/\s+as\s+/)[0]
        if (id) imported.add(id)
      }
    }
    const kit = [...reach(imported, 2)].sort()
    const specific = [...imported].filter((i) => /^[A-Z]/.test(i) && !KIT.has(i)).sort()
    return { name, area: relative(pagesDir, file).split('/')[0], pat: pattern(name), kit, specific }
  })

const lines = [
  '# UI page matrix',
  '',
  'Generated by `node scripts/ui-page-matrix.mjs`; do not edit by hand. CI fails when it is stale.',
  '',
  "Kit pieces are found by following each page's UI-package imports two levels deep. A page whose Kit column is",
  'empty is building its own structure and needs a design decision (see `DESIGN_CHANGE.md`). Page-specific',
  'pieces are domain components (a plan form, a charge row); they may not re-implement a kit pattern.',
  '',
  `${rows.length} route pages.`,
  '',
  '| Area | Page | Pattern | Kit pieces | Page-specific pieces |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| ${r.area} | \`${r.name}\` | ${r.pat} | ${r.kit.join(', ') || '—'} | ${r.specific.join(', ') || '—'} |`,
  ),
  '',
]
const text = lines.join('\n')

if (process.argv.includes('--check')) {
  const have = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (have !== text) {
    console.error('docs/ui-page-matrix.md is stale. Run: node scripts/ui-page-matrix.mjs')
    process.exit(1)
  }
  console.log('ui page matrix is current')
} else {
  writeFileSync(out, text)
  console.log(`wrote ${out} (${rows.length} pages)`)
}
